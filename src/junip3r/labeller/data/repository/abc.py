from typing import Protocol, Tuple, List, Optional

import numpy as np

from junip3r.labeller.data.types.abc import IInstanceType, IInstance

TemporalContext = Tuple[List[np.ndarray], np.ndarray, List[np.ndarray]]


class ILabellerConfigRepository(Protocol):
    def get_instance_types(self) -> List[IInstanceType]: ...
    def get_expected_instances(self, image_index: int) -> List[IInstanceType]: ...
    def get_tag_names(self) -> List[str]: ...


class ILabelRepository(Protocol):
    def get_instances(self, image_index: int) -> List[IInstance]: ...
    def set_instances(self, image_index: int, instances: List[IInstance]): ...


class IImageRepository(Protocol):
    def get_num_images(self) -> int: ...
    def get_image(self, image_index: int) -> np.ndarray: ...
    def get_image_name(self, image_index: int) -> str: ...


class IContextRepository(Protocol):
    def get_context(self, image_index: int) -> Optional[TemporalContext]: ...


class IMetadataRepository(Protocol):
    def get_notes(self, image_index: int) -> str: ...
    def set_notes(self, image_index: int, notes: str): ...

    def get_tags(self, image_index: int) -> List[str]: ...
    def set_tags(self, image_index: int, tags: List[str]): ...


class ISettingsRepository(Protocol):
    def get_settings(self, image_index: int) -> Tuple[float, float]: ...
    def set_settings(self, image_index: int, brightness: float, contrast: float): ...


class IPointSelectionRepository(Protocol):
    def get_selection(self, image_index: int) -> Tuple[Optional[str], Optional[int]]: ...
    def set_selection(self, image_index: int, instance_id: str, point_index: int): ...

    def get_new_instance_type_index(self, image_index: int) -> int: ...
    def set_new_instance_type_index(self, image_index: int, instance_type_index: int): ...
