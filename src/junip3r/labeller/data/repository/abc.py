from pathlib import Path
from typing import Protocol, Tuple, Optional, Sequence

import numpy as np

from junip3r.common.labels.data import Instance as DataInstance
from junip3r.common.tags.data import Tags
from junip3r.labeller.config.data import InstanceType
from junip3r.labeller.data.types.abc import TemporalContext, Selection


class IConfigRepository(Protocol):
    def get_instance_types(self, image_index: int) -> Sequence[InstanceType]: ...
    def get_expected_instances(self, image_index: int) -> Sequence[InstanceType]: ...
    def get_tag_names(self, image_index: int) -> Sequence[str]: ...


class ILabelRepository(Protocol):
    """Type-unaware: pure DTO I/O. Type resolution into color/id-attached, mutable
    working instances is LabelModel's job (labeller/model/label_model.py), not the
    repository's - see JuniperLabelRepository for the concrete implementation.
    """
    def get_instances(self, image_index: int) -> Sequence[DataInstance]: ...
    def set_instances(self, image_index: int, instances: Sequence[DataInstance]) -> None: ...


class IImageRepository(Protocol):
    def get_num_images(self) -> int: ...
    def get_image(self, image_index: int) -> np.ndarray: ...
    def get_image_name(self, image_index: int) -> str: ...
    def get_image_file(self, image_index: int) -> Optional[Path]: ...


class IContextRepository(Protocol):
    def get_context(self, image_index: int) -> Optional[TemporalContext]: ...


class IMetadataRepository(Protocol):
    def get_notes(self, image_index: int) -> str: ...
    def set_notes(self, image_index: int, notes: str): ...


class ITagRepository(Protocol):
    def get_tags(self, image_index: int) -> Tags: ...
    def set_tags(self, image_index: int, tags: Tags): ...


class ISettingsRepository(Protocol):
    def get_settings(self, image_index: int) -> Tuple[float, float]: ...
    def set_settings(self, image_index: int, brightness: float, contrast: float): ...


class ISelectionRepository(Protocol):
    def get_selection(self, image_index: int) -> Optional[Selection]: ...
    def set_selection(self, image_index: int, selection: Optional[Selection]): ...

    def get_new_instance_type(self, image_index: int) -> Optional[InstanceType]: ...
    def set_new_instance_type(self, image_index: int, instance_type: Optional[InstanceType]): ...
